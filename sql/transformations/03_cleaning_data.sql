-- code for ETL stage on the staging area_Leeds2016 table -- 
SELECT * FROM STAGING_LEEDS2016;
ALTER TABLE STAGING_LEEDS2016 ADD (
    ROAD_CLASS_CODE NUMBER,
    ROAD_SURFACE_CODE NUMBER,
    LIGHTING_CODE NUMBER,
    WEATHER_CODE NUMBER
);
UPDATE STAGING_LEEDS2016
SET ROAD_CLASS_CODE = CASE
    WHEN ROAD_CLASS = 'Motorway' THEN 1
    WHEN ROAD_CLASS = 'A(M)' THEN 2
    WHEN ROAD_CLASS = 'A' THEN 3
    WHEN ROAD_CLASS = 'B' THEN 4
    WHEN ROAD_CLASS = 'C' THEN 5
    WHEN ROAD_CLASS = 'Unclassified' THEN 6
    ELSE NULL
END;
UPDATE STAGING_LEEDS2016
SET ROAD_SURFACE_CODE = CASE
    WHEN ROAD_SURFACE = 'Dry' THEN 1
    WHEN ROAD_SURFACE = 'Wet / Damp' THEN 2
    WHEN ROAD_SURFACE = 'Snow' THEN 3
    WHEN ROAD_SURFACE = 'Frost / Ice' THEN 4
    WHEN ROAD_SURFACE = 'Flood (surface water over 3cm deep)' THEN 5
    WHEN ROAD_SURFACE = 'Unknown' THEN 9
    ELSE NULL
END;
UPDATE STAGING_LEEDS2016
SET LIGHTING_CODE = CASE
    WHEN LIGHTING_CONDITIONS = 'Daylight: street lights present' THEN 1
    WHEN LIGHTING_CONDITIONS = 'Daylight: no street lighting' THEN 2
    WHEN LIGHTING_CONDITIONS = 'Daylight: street lighting unknown' THEN 3
    WHEN LIGHTING_CONDITIONS = 'Darkness: street lights present and lit' THEN 4
    WHEN LIGHTING_CONDITIONS = 'Darkness: street lights present but unlit' THEN 5
    WHEN LIGHTING_CONDITIONS = 'Darkness: no street lighting' THEN 6
    WHEN LIGHTING_CONDITIONS = 'Darkness: street lighting unknown' THEN 7
    ELSE NULL
END;
UPDATE STAGING_LEEDS2016
SET WEATHER_CODE = CASE
    WHEN WEATHER_CONDITIONS = 'Fine without high winds' THEN 1
    WHEN WEATHER_CONDITIONS = 'Raining without high winds' THEN 2
    WHEN WEATHER_CONDITIONS = 'Snowing without high winds' THEN 3
    WHEN WEATHER_CONDITIONS = 'Fine with high winds' THEN 4
    WHEN WEATHER_CONDITIONS = 'Raining with high winds' THEN 5
    WHEN WEATHER_CONDITIONS = 'Snowing with high winds' THEN 6
    WHEN WEATHER_CONDITIONS = 'Fog or mist – if hazard' THEN 7
    WHEN WEATHER_CONDITIONS = 'Other' THEN 8
    WHEN WEATHER_CONDITIONS = 'Unknown' THEN 9
    ELSE NULL
END;

SELECT ROAD_CLASS, ROAD_CLASS_CODE,
       ROAD_SURFACE, ROAD_SURFACE_CODE,
       LIGHTING_CONDITIONS, LIGHTING_CODE,
       WEATHER_CONDITIONS, WEATHER_CODE
FROM STAGING_LEEDS2016
FETCH FIRST 50 ROWS ONLY;

