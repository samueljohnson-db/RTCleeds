    WHEN VEHICLE_TYPE = 'Bus or coach (17 or more passenger seats)' THEN 11
    WHEN VEHICLE_TYPE = 'Other motor vehicle' THEN 14
    WHEN VEHICLE_TYPE = 'Other non-motor vehicle' THEN 15
    WHEN VEHICLE_TYPE = 'Ridden horse' THEN 16
    WHEN VEHICLE_TYPE = 'Agricultural vehicle (includes diggers etc.)' THEN 17
    WHEN VEHICLE_TYPE = 'Tram / Light rail' THEN 18
    WHEN VEHICLE_TYPE = 'Goods vehicle 3.5 tonnes mgw and under' THEN 19
    WHEN VEHICLE_TYPE = 'Goods vehicle over 3.5 tonnes and under 7.5 tonnes mgw' THEN 20
