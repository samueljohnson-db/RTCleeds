INSERT INTO FACT_INCIDENT_WEATHER (
    INCIDENT_KEY, REFERENCE_NUMBER, DATE_KEY, WEATHER_KEY, LIGHTING_KEY, ROAD_KEY,
    CASUALTY_KEY, VEHICLE_KEY, ROAD_CLASS, NUMBER_OF_VEHICLES, CASUALTY_SEVERITY_CODE,
    AGE_OF_CASUALTY, HOUR, WX_WIND_DIR_12M, WX_WIND_SPD_12M_MS, WX_WIND_STD,
    WX_TEMP_8M_DEGC, WX_TEMP_DIFF_2M, WX_GLOB_RAD_WM2, WX_REL_HUM_PCT,
    WEATHER_TIME_GAP_MINUTES, YEAR, SEVERITY_KEY
)
SELECT
    FACT_INCIDENT_WEATHER_SEQ.NEXTVAL,
    j.REFERENCE_NUMBER,
    dd.DATE_KEY,
    dw.WEATHER_KEY,
    dli.LIGHTING_KEY,
    dr.ROAD_KEY,
    NULL,
    dv.VEHICLE_KEY,
    j.ROAD_CLASS,
    j.NUMBER_OF_VEHICLES,
    j.CASUALTY_SEVERITY,
    j.AGE_OF_CASUALTY,
    TO_NUMBER(TO_CHAR(j.FULL_DATE_CORRECT, 'HH24')),
    j.WIND_DIRECTION,
    j.WIND_SPEED,
    j.WIND_STD,
    j.TEMP_8M,
    j.TEMP_DIFF,
    j.GLOBAL_RADIATION,
    j.REL_HUMIDITY,
    j.gap_minutes,
    EXTRACT(YEAR FROM j.FULL_DATE_CORRECT),
    dsv.SEVERITY_KEY
FROM (
    SELECT
        x.*,
        ROW_NUMBER() OVER (
            PARTITION BY x.REFERENCE_NUMBER, x.CASUALTY_NUMBER
            ORDER BY x.gap_minutes
        ) AS rn
    FROM (
        SELECT
            inc.*,
            wx.WIND_DIRECTION,
            wx.WIND_SPEED,
            wx.WIND_STD,
            wx.TEMP_8M,
            wx.TEMP_DIFF,
            wx.GLOBAL_RADIATION,
            wx.REL_HUMIDITY,
            ABS((inc.FULL_DATE_CORRECT - wx.FULL_TS) * 1440) AS gap_minutes
        FROM (
            SELECT
                i.*,
                TRUNC(i.FULL_DATE_CORRECT)
                    + ROUND((i.FULL_DATE_CORRECT - TRUNC(i.FULL_DATE_CORRECT)) * 1440 / 15) * 15 / 1440
                    AS ROUNDED_TS
            FROM STAGING_INCIDENT_JOINED i
            WHERE i.FULL_DATE_CORRECT IS NOT NULL
        ) inc
        JOIN (
            SELECT
                w.*,
                TRUNC(w.FULL_TS)
                    + ROUND((w.FULL_TS - TRUNC(w.FULL_TS)) * 1440 / 15) * 15 / 1440
                    AS ROUNDED_TS
            FROM STAGING_WEATHER w
        ) wx
            ON inc.ROUNDED_TS = wx.ROUNDED_TS
    ) x
) j
JOIN DIM_DATE     dd  ON dd.FULL_DATE = TRUNC(j.FULL_DATE_CORRECT)
JOIN DIM_WEATHER  dw  ON dw.WEATHER_CODE = j.WEATHER_CODE
JOIN DIM_LIGHTING dli ON dli.LIGHTING_CODE = j.LIGHTING_CODE
JOIN DIM_ROAD     dr  ON dr.ROAD_SURFACE_CODE = j.ROAD_SURFACE_CODE
JOIN DIM_SEVERITY dsv ON dsv.CASUALTY_SEVERITY_CODE = j.CASUALTY_SEVERITY
JOIN DIM_VEHICLE  dv  ON dv.VEHICLE_TYPE_CODE = j.VEHICLE_1
WHERE j.rn = 1;

COMMIT;

