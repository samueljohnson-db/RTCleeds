INSERT INTO FACT_INCIDENT_WEATHER (
    INCIDENT_KEY, REFERENCE_NUMBER, DATE_KEY, WEATHER_KEY, LIGHTING_KEY, ROAD_KEY,
    CASUALTY_KEY, VEHICLE_KEY, ROAD_CLASS, NUMBER_OF_VEHICLES, CASUALTY_SEVERITY_CODE,
    AGE_OF_CASUALTY, HOUR, TIME_PERIOD, WX_WIND_DIR_12M, WX_WIND_SPD_12M_MS, WX_WIND_STD,
    WX_TEMP_8M_DEGC, WX_TEMP_DIFF_2M, WX_GLOB_RAD_WM2, WX_REL_HUM_PCT,
    WEATHER_TIME_GAP_MINUTES, INCIDENT_COUNT
)
SELECT
    FACT_INCIDENT_WEATHER_SEQ.NEXTVAL,
    s.REFERENCE_NUMBER,
    TO_NUMBER(TO_CHAR(TO_TIMESTAMP(s.INC_TIMESTAMP, 'DD/MM/YYYY HH24:MI'), 'YYYYMMDD')),
    w.WEATHER_KEY,
    l.LIGHTING_KEY,
    r.ROAD_KEY,
    c.CASUALTY_KEY,
    v.VEHICLE_KEY,
    TO_NUMBER(s.ROAD_CLASS),
    TO_NUMBER(s.NUMBER_OF_VEHICLES),
    TO_NUMBER(s.CASUALTY_SEVERITY),
    TO_NUMBER(s.AGE_OF_CASUALTY),
    TO_NUMBER(TO_CHAR(TO_TIMESTAMP(s.INC_TIMESTAMP, 'DD/MM/YYYY HH24:MI'), 'HH24')),
    CASE
        WHEN TO_CHAR(TO_TIMESTAMP(s.INC_TIMESTAMP, 'DD/MM/YYYY HH24:MI'), 'HH24') BETWEEN '06' AND '11' THEN 'Morning'
        WHEN TO_CHAR(TO_TIMESTAMP(s.INC_TIMESTAMP, 'DD/MM/YYYY HH24:MI'), 'HH24') BETWEEN '12' AND '17' THEN 'Afternoon'
        WHEN TO_CHAR(TO_TIMESTAMP(s.INC_TIMESTAMP, 'DD/MM/YYYY HH24:MI'), 'HH24') BETWEEN '18' AND '23' THEN 'Evening'
        ELSE 'Night'
    END,
    TO_NUMBER(s.WX_WIND_DIR_12M),
    TO_NUMBER(s.WX_WIND_SPD_12M_MS),
    TO_NUMBER(s.WX_WIND_STD),
    TO_NUMBER(s.WX_TEMP_8M_DEGC),
    TO_NUMBER(s.WX_TEMP_DIFF_2M),
    TO_NUMBER(s.WX_GLOB_RAD_WM2),
    TO_NUMBER(s.WX_REL_HUM_PCT),
    TO_NUMBER(s.WEATHER_TIME_GAP_MINUTES),
    1
FROM STAGING_MASTER s
LEFT JOIN DIM_WEATHER  w ON w.WEATHER_CODE = TO_NUMBER(s.WEATHER_CODE)
LEFT JOIN DIM_LIGHTING l ON l.LIGHTING_CODE = TO_NUMBER(s.LIGHTING_CODE)
LEFT JOIN DIM_ROAD     r ON r.ROAD_SURFACE_CODE = TO_NUMBER(s.ROAD_SURFACE_CODE)
LEFT JOIN DIM_VEHICLE  v ON v.VEHICLE_TYPE_CODE = TO_NUMBER(s.VEHICLE_1)
LEFT JOIN DIM_CASUALTY c ON c.CASUALTY_CLASS =
    CASE TO_NUMBER(s.CASUALTY_CLASS)
        WHEN 1 THEN 'Driver or rider'
        WHEN 2 THEN 'Vehicle or pillion passenger'
        WHEN 3 THEN 'Pedestrian'
    END
WHERE s.INC_TIMESTAMP IS NOT NULL
LOG ERRORS REJECT LIMIT UNLIMITED;

COMMIT;

