INSERT INTO DIM_DATE (DATE_KEY, FULL_DATE, DAY, MONTH, QUARTER, YEAR)
SELECT DISTINCT
    TO_NUMBER(TO_CHAR(t.ts, 'YYYYMMDD')),
    TRUNC(t.ts),
    TO_NUMBER(TO_CHAR(t.ts, 'DD')),
    TO_CHAR(t.ts, 'Month'),
    TO_NUMBER(TO_CHAR(t.ts, 'Q')),
    TO_NUMBER(TO_CHAR(t.ts, 'YYYY'))
FROM (
    SELECT TO_TIMESTAMP(s.INC_TIMESTAMP, 'DD/MM/YYYY HH24:MI') AS ts
    FROM STAGING_MASTER s
    WHERE s.INC_TIMESTAMP IS NOT NULL
) t
WHERE NOT EXISTS (
    SELECT 1 FROM DIM_DATE d
    WHERE d.DATE_KEY = TO_NUMBER(TO_CHAR(t.ts, 'YYYYMMDD'))
);

